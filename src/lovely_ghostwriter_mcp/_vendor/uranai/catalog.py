def required_inputs(systems: list[str]) -> list[str]:
    req = ["question", "name_kana"]  # ブリーフ§2: 占ってほしいこと・ふりがなは全員必須
    for s in systems:
        for r in CATALOG[s]["required_inputs"]:
            if r not in req:
                req.append(r)
    return req


def blend_label(systems: list[str]) -> str:
    return "×".join(CATALOG[s]["name"] for s in systems)


